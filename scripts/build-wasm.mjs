/**
 * Build the Rust compute core and copy the wasm artifact into public/.
 * The artifact is committed so the app runs without a Rust toolchain.
 */
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { copyFileSync, existsSync, mkdirSync, readFileSync, renameSync, statSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const crate = resolve(root, 'wasm')
const wasm = resolve(crate, 'target/wasm32-unknown-unknown/release/prop_core.wasm')
const target = resolve(root, 'public/wasm/prop_core.wasm')

execFileSync('cargo', ['build', '--release', '--target', 'wasm32-unknown-unknown'], {
  cwd: crate,
  stdio: 'inherit',
})

mkdirSync(resolve(root, 'public/wasm'), { recursive: true })
copyFileSync(wasm, target)

// Optional post-pass: binaryen's wasm-opt typically removes another 10–15%
// from a serde-based module. It is a dev dependency, so the step is skipped
// (with a note) on machines that have not installed it.
const wasmOpt = resolve(root, 'node_modules/binaryen/bin/wasm-opt')
if (existsSync(wasmOpt)) {
  const optimized = `${target}.opt`
  try {
    execFileSync(
      wasmOpt,
      [
        '-Oz',
        '--strip-debug',
        '--strip-dwarf',
        '--strip-producers',
        '--enable-bulk-memory',
        '--enable-bulk-memory-opt',
        '--enable-nontrapping-float-to-int',
        '--enable-sign-ext',
        '-o',
        optimized,
        target,
      ],
      { stdio: 'inherit' },
    )
    if (statSync(optimized).size < statSync(target).size) renameSync(optimized, target)
    else execFileSync('rm', ['-f', optimized])
  } catch (error) {
    console.warn(`wasm-opt skipped: ${error instanceof Error ? error.message : String(error)}`)
  }
} else {
  console.log('wasm-opt not installed; run bun install to enable the size post-pass')
}
const size = statSync(target).size
const hash = createHash('sha256').update(readFileSync(target)).digest('hex').slice(0, 16)
mkdirSync(resolve(root, 'app/wasm'), { recursive: true })
writeFileSync(
  resolve(root, 'app/wasm/artifact.ts'),
  `// Generated by scripts/build-wasm.mjs. Do not edit by hand.\nexport const wasmArtifactVersion = '${hash}'\n`,
)
console.log(`prop_core.wasm copied (${(size / 1024).toFixed(1)} KiB) -> public/wasm/prop_core.wasm`)
console.log(`artifact version ${hash} -> app/wasm/artifact.ts`)
console.log('Restart the dev server and hard-reload the page to pick up a new core.')
